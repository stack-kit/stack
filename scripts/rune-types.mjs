// The types of the rune modules. A module that uses runes outside a component ships as a .svelte.js
// file with its types in JSDoc, and with a committed .svelte.d.ts next to it. The dev server of a
// product does not compile a .svelte.ts file inside a package, so no such file ships. tsc writes the
// .svelte.d.ts from the JSDoc, and this script holds the two in step. It does the same for each plain
// module of PLAIN, which a shipped TypeScript file imports from outside preview/src/lib: TypeScript in a
// product reads no JavaScript file inside node_modules, so such a module ships with its .d.mts.
//
//   node scripts/rune-types.mjs           writes each .svelte.d.ts from its .svelte.js, and each .d.mts
//   node scripts/rune-types.mjs --check   writes nothing, and exits 1 when a .svelte.d.ts differs from
//     the output of tsc, when tsc reports an error in a .svelte.js, or when a .svelte.ts is in a
//     folder that ships
//
// It reads the folders of preview/src/lib that ship (SHIPPED), and it loads TypeScript from
// preview/node_modules. It runs from any folder.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const LIB = join(ROOT, 'preview/src/lib');
const SHIPPED = ['components', 'hooks', 'outside', 'print', 'stack'];
const PLAIN = ['scripts/lib/email-roles.mjs'];
const HEADER = (js) => `// Generated by scripts/rune-types.mjs from the JSDoc of ${js}. Do not edit it by hand: change ${js}, then run "node scripts/rune-types.mjs".\n`;

/** The files under dir whose names end with suffix, as sorted absolute paths. */
function walk(dir, suffix) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p, suffix));
    else if (e.name.endsWith(suffix)) out.push(p);
  }
  return out.sort();
}

function loadTypeScript() {
  try {
    return createRequire(join(ROOT, 'preview/package.json'))('typescript');
  } catch {
    throw new Error('TypeScript is not in preview/node_modules. Run "npm ci" in preview/.');
  }
}

/**
 * The declarations that tsc writes for each module, and the errors that it reports in them. The
 * committed .svelte.d.ts files stay out of the program, so the output comes from the .js files only.
 */
export function emit(modules, ts = loadTypeScript()) {
  const options = {
    allowJs: true,
    checkJs: true,
    strict: true,
    declaration: true,
    emitDeclarationOnly: true,
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    newLine: ts.NewLineKind.LineFeed,
    skipLibCheck: true,
    types: [],
  };
  const hidden = new Set(modules.map((m) => m.replace(/\.(m?)js$/, '.d.$1ts')));
  const host = ts.createCompilerHost(options);
  const fileExists = host.fileExists;
  host.fileExists = (f) => !hidden.has(f) && fileExists(f);
  const program = ts.createProgram(modules, options, host);
  const errors = ts
    .getPreEmitDiagnostics(program)
    .filter((d) => d.file && modules.includes(d.file.fileName))
    .map((d) => {
      const { line } = d.file.getLineAndCharacterOfPosition(d.start ?? 0);
      return `${relative(ROOT, d.file.fileName)}:${line + 1}: ${ts.flattenDiagnosticMessageText(d.messageText, ' ')}`;
    });
  const out = new Map();
  program.emit(undefined, (name, text) => {
    const js = name.replace(/\.d\.(m?)ts$/, '.$1js');
    if (modules.includes(js)) out.set(name, HEADER(basename(js)) + text);
  });
  return { errors, out: new Map([...out].sort(([a], [b]) => (a < b ? -1 : 1))) };
}

function main(argv) {
  const unknown = argv.filter((a) => a !== '--check');
  if (unknown.length) throw new Error(`unknown argument "${unknown[0]}". Give no argument to write the .svelte.d.ts files, or --check to compare them.`);
  const check = argv.includes('--check');
  const folders = SHIPPED.map((f) => join(LIB, f));
  const sources = folders.flatMap((f) => walk(f, '.svelte.ts'));
  for (const f of sources) console.error(`rune-types: ${relative(ROOT, f)} is TypeScript in a folder that ships, and the dev server of a product cannot load it. Write it as a .svelte.js with JSDoc, then run "node scripts/rune-types.mjs".`);
  const runes = folders.flatMap((f) => walk(f, '.svelte.js'));
  if (!runes.length) throw new Error(`no .svelte.js file in ${SHIPPED.map((f) => `preview/src/lib/${f}/`).join(', ')}.`);
  const modules = [...runes, ...PLAIN.map((f) => join(ROOT, f))];
  const { errors, out } = emit(modules);
  for (const e of errors) console.error(`rune-types: ${e}`);
  if (errors.length) {
    console.error(`rune-types: tsc reports ${errors.length} errors in the .svelte.js files, so their types are not sure. Correct the JSDoc${check ? '' : ', then run it again. Nothing was written'}.`);
    return 1;
  }
  if (!check) {
    for (const [dts, text] of out) writeFileSync(dts, text);
    console.log(`rune-types: wrote ${out.size} declaration files: ${[...out.keys()].map((f) => relative(ROOT, f)).join(', ')}`);
    return sources.length ? 1 : 0;
  }
  let match = 0;
  for (const [dts, want] of out) {
    const at = relative(ROOT, dts);
    const have = existsSync(dts) ? readFileSync(dts, 'utf8') : null;
    if (have === want) {
      match++;
      continue;
    }
    if (have === null) {
      console.error(`rune-types: ${at} does not exist. Run "node scripts/rune-types.mjs", and commit the file with its JavaScript file.`);
      continue;
    }
    const a = have.split('\n');
    const b = want.split('\n');
    const line = a.findIndex((l, i) => l !== b[i]);
    console.error(`rune-types: ${at} differs from the output of tsc for its JavaScript file, first at line ${(line < 0 ? b.length : line) + 1}. Run "node scripts/rune-types.mjs", and commit the file with its JavaScript file.`);
  }
  const orphans = folders.flatMap((f) => walk(f, '.svelte.d.ts')).filter((d) => !existsSync(d.replace(/\.d\.ts$/, '.js')));
  for (const d of orphans) console.error(`rune-types: ${relative(ROOT, d)} has no .svelte.js beside it. Delete it, or add its .svelte.js.`);
  console.log(`rune-types: ${match} of ${out.size} match: ${[...out.keys()].map((f) => relative(ROOT, f)).join(', ')}`);
  return match === out.size && !sources.length && !orphans.length ? 0 : 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (e) {
    console.error(`rune-types: ${e.message}`);
    process.exitCode = 1;
  }
}
